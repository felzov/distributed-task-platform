"""Alembic environment: runs the hand-written revisions in `versions/` over asyncpg (ADR 0003).

Migrations are never autogenerated, so there is no target metadata and no offline (`--sql`) mode.
"""

import asyncio
from logging.config import fileConfig

from alembic import context
from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import create_async_engine

from task_platform.config import Settings

config = context.config

# Only the CLI loads alembic.ini; tests build a Config without a file and keep their logging setup.
if config.config_file_name is not None:
    fileConfig(config.config_file_name)


def _settings() -> Settings:
    # Integration tests pass settings for the `_test` database; the CLI reads DATABASE_URL.
    if "settings" not in config.attributes:
        return Settings()
    settings = config.attributes["settings"]
    # Fail loudly: a silent fallback would migrate (or downgrade) the dev database instead.
    if not isinstance(settings, Settings):
        raise TypeError("config.attributes['settings'] must be a Settings instance")
    return settings


def _run_migrations(connection: Connection) -> None:
    context.configure(connection=connection)
    with context.begin_transaction():
        context.run_migrations()


async def _run_async_migrations() -> None:
    settings = _settings()
    # No statement_timeout here, unlike the app engine: a migration may legitimately run longer.
    engine = create_async_engine(
        settings.database_url.get_secret_value(),
        poolclass=pool.NullPool,
        hide_parameters=True,
        connect_args={"timeout": settings.db_connect_timeout_s},
    )
    try:
        async with engine.connect() as connection:
            await connection.run_sync(_run_migrations)
    finally:
        await engine.dispose()


if context.is_offline_mode():
    raise RuntimeError("offline (--sql) mode is not supported; run migrations against a database")
asyncio.run(_run_async_migrations())
